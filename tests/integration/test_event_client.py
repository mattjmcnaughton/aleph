"""The ``client`` event dimension over both credentials (AL-613, TDD §12, D18).

Product events carry a server-derived ``client``: ``web`` for a cookie request,
the ``OIDC_CLIENT_MAP`` label of a bearer token's client id (``ios``), else
``unknown``. Real routes, real Postgres, the real ``BearerAuthenticator`` over
the in-memory JWKS fake (``tests/_bearer_fakes.py``), and the events captured
where Logfire would receive them (``capfire``). ``outline_generated`` fires from
the generation task the request spawned, so it also proves that background work
inherits the request's client. Events from work no request started (the
scheduled job, AL-615) carry none: ``tests/unit/test_events.py``.
"""

from __future__ import annotations

from typing import TYPE_CHECKING, Any

import pytest
from httpx import ASGITransport, AsyncClient

from aleph import events
from aleph.app import create_app
from aleph.auth import AuthIdentity
from aleph.bearer import get_bearer_authenticator
from aleph.config import settings
from aleph.logging import configure_logging
from aleph.services import generation as gen_module
from tests._bearer_fakes import ISSUER, USERINFO, fake_authenticator, mint

from .conftest import CollectingSpawn, captured_records, stub_resolver

if TYPE_CHECKING:
    from fastapi import FastAPI

# The cookie identity is the bearer token's ``(iss, sub)``: one learner, two clients.
LEARNER = AuthIdentity(
    issuer=ISSUER,
    subject="subject-1",
    username="dev",
    display_name="Dev User",
    email="dev@example.com",
)


class StubOAuthClient:
    async def authorize_access_token(self, _request: object) -> dict[str, str]:
        return {"access_token": "stub"}


@pytest.fixture
def app(monkeypatch: pytest.MonkeyPatch) -> FastAPI:
    monkeypatch.setattr(settings, "oidc_client_map", "aleph-ios:ios")
    application = create_app()
    authenticator = fake_authenticator(USERINFO)
    application.dependency_overrides[get_bearer_authenticator] = lambda: authenticator
    return application


@pytest.fixture
def spawn(monkeypatch: pytest.MonkeyPatch) -> CollectingSpawn:
    collector = CollectingSpawn()
    monkeypatch.setattr(
        gen_module.generation_orchestrator, "_resolve_model", stub_resolver()
    )
    monkeypatch.setattr(gen_module.generation_orchestrator, "_spawn", collector)
    return collector


def _client(app: FastAPI) -> AsyncClient:
    return AsyncClient(transport=ASGITransport(app=app), base_url="http://testserver")


async def _sign_in(client: AsyncClient, monkeypatch: pytest.MonkeyPatch) -> None:
    monkeypatch.setattr(
        "aleph.routers.auth.oauth.create_client", lambda _p: StubOAuthClient()
    )
    monkeypatch.setattr("aleph.routers.auth.fetch_identity", lambda *_a: LEARNER)
    resp = await client.get("/auth/callback", follow_redirects=False)
    assert resp.status_code == 303


async def _create_path(
    client: AsyncClient, spawn: CollectingSpawn, topic: str, **kwargs: Any
) -> str:
    resp = await client.post(
        "/api/v1/paths", json={"topic": topic, "level": "new_to_it"}, **kwargs
    )
    assert resp.status_code == 202, resp.text
    # The outline is generated by the task this request spawned.
    await spawn.drain()
    return resp.json()["id"]


def _clients_by_path(capfire: Any, name: str) -> dict[str, object]:
    return {
        record["attributes"]["path_id"]: record["attributes"].get("client")
        for record in captured_records(capfire, name)
    }


def _account_created_clients(capfire: Any) -> list[object]:
    return [
        record["attributes"].get("client")
        for record in captured_records(capfire, events.ACCOUNT_CREATED)
    ]


def _bearer(**claims: Any) -> dict[str, str]:
    return {"Authorization": f"Bearer {mint(**claims)}"}


@pytest.mark.anyio
async def test_cookie_events_carry_web(
    app: FastAPI,
    spawn: CollectingSpawn,
    monkeypatch: pytest.MonkeyPatch,
    capfire: Any,
) -> None:
    configure_logging()
    async with _client(app) as client:
        await _sign_in(client, monkeypatch)
        path_id = await _create_path(client, spawn, "Rust ownership")

    assert _account_created_clients(capfire) == ["web"]
    assert _clients_by_path(capfire, events.PATH_CREATED) == {path_id: "web"}
    assert _clients_by_path(capfire, events.OUTLINE_GENERATED) == {path_id: "web"}


@pytest.mark.anyio
async def test_the_ios_clients_events_carry_ios(
    app: FastAPI, spawn: CollectingSpawn, capfire: Any
) -> None:
    configure_logging()
    async with _client(app) as client:
        # The first bearer request provisions the account, too.
        path_id = await _create_path(
            client, spawn, "Tide pools", headers=_bearer(azp="aleph-ios")
        )

    assert _account_created_clients(capfire) == ["ios"]
    assert _clients_by_path(capfire, events.PATH_CREATED) == {path_id: "ios"}
    assert _clients_by_path(capfire, events.OUTLINE_GENERATED) == {path_id: "ios"}


@pytest.mark.anyio
async def test_a_client_id_claim_maps_like_azp(
    app: FastAPI, spawn: CollectingSpawn, capfire: Any
) -> None:
    configure_logging()
    async with _client(app) as client:
        path_id = await _create_path(
            client,
            spawn,
            "Tide pools",
            headers=_bearer(azp=None, client_id="aleph-ios"),
        )

    assert _clients_by_path(capfire, events.PATH_CREATED) == {path_id: "ios"}


@pytest.mark.anyio
async def test_an_unmapped_bearer_client_carries_unknown(
    app: FastAPI, spawn: CollectingSpawn, capfire: Any
) -> None:
    configure_logging()
    async with _client(app) as client:
        path_id = await _create_path(
            client, spawn, "Tide pools", headers=_bearer(azp="some-other-app")
        )

    assert _account_created_clients(capfire) == ["unknown"]
    assert _clients_by_path(capfire, events.PATH_CREATED) == {path_id: "unknown"}
    assert _clients_by_path(capfire, events.OUTLINE_GENERATED) == {path_id: "unknown"}


@pytest.mark.anyio
async def test_one_learner_on_both_clients_is_attributed_per_request(
    app: FastAPI,
    spawn: CollectingSpawn,
    monkeypatch: pytest.MonkeyPatch,
    capfire: Any,
) -> None:
    """Interleaved requests on one connection pool: no request's client leaks
    into the next, whichever credential it carries."""
    configure_logging()
    async with _client(app) as client:
        await _sign_in(client, monkeypatch)
        on_web = await _create_path(client, spawn, "Rust ownership")
        on_ios = await _create_path(
            client, spawn, "Tide pools", headers=_bearer(azp="aleph-ios")
        )
        on_web_again = await _create_path(client, spawn, "Bread baking")

    assert _clients_by_path(capfire, events.PATH_CREATED) == {
        on_web: "web",
        on_ios: "ios",
        on_web_again: "web",
    }
    assert _clients_by_path(capfire, events.OUTLINE_GENERATED) == {
        on_web: "web",
        on_ios: "ios",
        on_web_again: "web",
    }
    # Each request binds its client in its own task; the caller's context
    # (here the test, standing in for whatever runs next) is never touched.
    assert events.request_client.get() is None
